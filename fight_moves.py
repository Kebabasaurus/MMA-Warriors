    result = {}
    for raw_key, raw_value in values.items():
        key = str(raw_key or "")
        known = key in MOVE_REGISTRY or (key.startswith("defense:") and key[8:] in DEFENSE_REGISTRY)
        if not known:
            continue
        try:
            value = int(round(float(raw_value)))
        except (TypeError, ValueError):
            continue
        result[key] = max(0, min(100, value))
    return result
