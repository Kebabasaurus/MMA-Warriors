DEFENSE_REGISTRY = {definition.defense_id: definition for definition in DEFENSE_DEFINITIONS}


def validate_defense_registry():
    issues = []
    known_skills = {key for group in DETAILED_SKILL_GROUPS.values() for key in group}
    if len(DEFENSE_REGISTRY) != len(DEFENSE_DEFINITIONS):
        issues.append("Defense IDs must be unique")
    for definition in DEFENSE_DEFINITIONS:
        if not definition.families:
            issues.append(f"{definition.defense_id}: requires a defense family")
        if not definition.positions or not definition.positions <= ALL_POSITIONS:
            issues.append(f"{definition.defense_id}: contains an unknown position")
        unknown = set(definition.skills) - known_skills
        if unknown:
            issues.append(f"{definition.defense_id}: unknown skills {', '.join(sorted(unknown))}")
    return issues


DEFENSE_REGISTRY_ERRORS = tuple(validate_defense_registry())
if DEFENSE_REGISTRY_ERRORS:
    raise ValueError("Invalid MMA defense registry: " + "; ".join(DEFENSE_REGISTRY_ERRORS))


def legal_defenses(families, position):
    families = set(families or ())
    return tuple(definition for definition in DEFENSE_DEFINITIONS
                 if position in definition.positions and families.intersection(definition.families))


def move(move_id, name, action, positions, **kwargs):
    return MoveDefinition(move_id, name, action, frozenset(positions), **kwargs)


