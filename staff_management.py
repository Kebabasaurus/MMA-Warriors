    def staff_refresh_brief_action_choices(self, _event=None):
        """Keep the brief action selector aligned with the capability matrix."""
        combo = getattr(self, "staff_brief_action_combo", None)
        action_list = getattr(self, "staff_brief_action_list", None)
        choice = getattr(self, "staff_brief_action_choice", None)
        department_var = getattr(self, "staff_brief_department_choice", None)
        if (combo is None and action_list is None) or choice is None or department_var is None:
            return
        capability = self.STAFF_CAPABILITIES.get(department_var.get(), {})
        hint = getattr(self, "staff_brief_target_hint", None)
        if hint is not None:
            if str(department_var.get() or "") == "Talent Relations":
                hint.config(text=(
                    "Talent Relations targets an existing contract-batch ID from Contracts "
                    "(for example contract-batch-000001); create/review the batch there first."
                ))
            else:
                hint.config(text="Targets use saved IDs; the brief never creates a new domain record.")
        actions = tuple(str(value) for value in capability.get("actions", ()) if value)
        labels = tuple(self.STAFF_ACTION_LABELS.get(action_id, action_id) for action_id in actions)
        current = choice.get()
        current_id = {self.STAFF_ACTION_LABELS.get(action_id, action_id): action_id for action_id in actions}.get(current, current)
        default = str(capability.get("default_action", actions[0] if actions else "") or "")
        default_id = current_id if current_id in actions else default
        if action_list is not None:
            prior_ids = []
            try:
                prior_labels = list(action_list.get(0, "end"))
                prior_ids = [
                    {self.STAFF_ACTION_LABELS.get(action_id, action_id): action_id for action_id in actions}.get(label, "")
                    for label in prior_labels
                ]
                selected_ids = [prior_ids[index] for index in action_list.curselection() if 0 <= int(index) < len(prior_ids)]
            except (AttributeError, TypeError, ValueError):
                selected_ids = []
            action_list.delete(0, "end")
            for label in labels:
                action_list.insert("end", label)
            selected_ids = [value for value in selected_ids if value in actions]
            if not selected_ids and default_id in actions:
                selected_ids = [default_id]
            for action_id in selected_ids:
                action_list.selection_set(actions.index(action_id))
            choice.set(self.STAFF_ACTION_LABELS.get(selected_ids[0], selected_ids[0]) if selected_ids else "")
        else:
            combo.configure(values=labels)
            choice.set(self.STAFF_ACTION_LABELS.get(default_id, default_id))

