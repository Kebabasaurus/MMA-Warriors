    def refresh_staff_management_panel(self):
        if not hasattr(self, "staff_brief_tree"):
            return
        # The Staff page is a reader.  Do not call the save-repairing
        # initialiser while repainting a malformed legacy envelope; explicit
        # brief/policy mutations and the completed-boundary worker own writes.
        state = getattr(self, "staff_management", {})
        if not isinstance(state, dict):
            state = {}
        if hasattr(self, "staff_autonomy_choice"):
            self.staff_sync_autonomy_choice()
        for name, key in (("staff_monthly_ceiling_entry", "monthly_ceiling"), ("staff_minimum_reserve_entry", "minimum_cash_reserve")):
            entry = getattr(self, name, None)
            if entry is not None:
                entry.delete(0, "end")
                entry.insert(0, str(state.get(key, 0)))
        action_entry = getattr(self, "staff_action_ceiling_entry", None)
        if action_entry is not None:
            action_caps = state.get("per_action_ceiling", {})
            if not isinstance(action_caps, dict):
                action_caps = {}
            action_entry.delete(0, "end")
            action_entry.insert(0, str(action_caps.get("*", 0)))
        selected = self.staff_brief_tree.selection()
        prior_brief_identity = ""
        if selected:
            prior_brief = getattr(self, "staff_brief_rows", {}).get(selected[0])
            if isinstance(prior_brief, dict):
                prior_brief_identity = str(prior_brief.get("brief_id", "") or "")
        self.staff_brief_tree.delete(*self.staff_brief_tree.get_children())
        self.staff_brief_rows = {}
        used_brief_rows = set()
        raw_briefs = state.get("briefs", [])
        briefs = raw_briefs[:100] if isinstance(raw_briefs, list) else []
        for index, brief in enumerate(briefs):
            if not isinstance(brief, dict):
                continue
            raw_actions = brief.get("allowed_action_ids", [])
            raw_actions = raw_actions if isinstance(raw_actions, list) else []
            selected_actions = [str(value) for value in raw_actions if value]
            raw_completed = brief.get("completed_action_ids", [])
            raw_completed = raw_completed if isinstance(raw_completed, list) else []
            completed_actions = {str(value) for value in raw_completed if value}
            action_progress = f"{len(completed_actions & set(selected_actions))}/{len(selected_actions)}"
            base_row_id = self._staff_brief_view_id(brief, index)
            row_id = base_row_id
            suffix = 2
            while row_id in used_brief_rows:
                row_id = f"{base_row_id}#{suffix}"
                suffix += 1
            used_brief_rows.add(row_id)
            self.staff_brief_rows[row_id] = brief
            raw_targets = brief.get("target_refs", [])
            raw_targets = raw_targets if isinstance(raw_targets, list) else []
            raw_work_ids = brief.get("work_ids", [])
            raw_work_ids = raw_work_ids if isinstance(raw_work_ids, list) else []
            self.staff_brief_tree.insert("", "end", iid=row_id, values=(
                brief.get("department", ""), brief.get("objective", ""), raw_targets[0] if raw_targets else "-",
                brief.get("status", "Draft"), brief.get("lead_name", "Unstaffed"), action_progress,
                len(raw_work_ids),
            ))
        if prior_brief_identity:
            restored = next((row_id for row_id, brief in self.staff_brief_rows.items()
                             if str(brief.get("brief_id", "") or "") == prior_brief_identity), "")
            if restored:
                self.staff_brief_tree.selection_set(restored)
        summary = self.staff_management_summary()
        evidence_audit = self.staff_evidence_audit(state)
        if hasattr(self, "staff_autonomy_status"):
            self.staff_autonomy_status.config(text=(
                f"Effective default: {summary['mode']} | {summary['active_briefs']} active brief(s) | {summary['exceptions']} exception(s). "
                f"Evidence audit: {evidence_audit['status']} ({evidence_audit['finding_count']} finding(s), "
                f"{evidence_audit['qualified_count']} qualified work item(s)). "
                "Advice never spends money or counts as completed work. Legacy Scout auto-assignment remains separate."
            ))
        if hasattr(self, "staff_capability_tree"):
            self.staff_capability_tree.delete(*self.staff_capability_tree.get_children())
            for row in self.staff_capability_matrix().values():
                department = row["department"]
                review_ids = ", ".join(
                    str(action_id) for action_id in row.get("safe_read_action_ids", []) if action_id
                ) or "None registered"
                self.staff_capability_tree.insert("", "end", iid=department, values=(
                    department, row.get("effective_mode", "Manual"), row.get("lead_name", "Unstaffed"),
                    "Yes" if row.get("advice_available") else "No", review_ids,
                    "Yes" if row.get("automation_available") else "No",
                ))
            self.staff_refresh_capability_detail()
        if hasattr(self, "staff_specialty_tree"):
            self.staff_specialty_tree.delete(*self.staff_specialty_tree.get_children())
            for member in getattr(self, "staff", []) or []:
                snapshot = self.staff_specialty_snapshot(member)
                progression = self.staff_progression_snapshot(member)
                if not isinstance(member, dict):
                    self.staff_specialty_tree.insert("", "end", values=(
                        "Unavailable staff record", "Unavailable", "Legacy row",
                        "Unknown", "Personality only", "No mechanic inferred",
                        "—",
                    ))
                    continue
                self.staff_specialty_tree.insert("", "end", values=(
                    snapshot.get("name", "Staff"), member.get("role", "Operations"),
                    member.get("specialty", "Operations"), snapshot.get("strength", "Descriptive"),
                    snapshot.get("classification", "Personality only"),
                    snapshot.get("advantages", "None claimed until a definition is approved."),
                    progression.get("progression_label", f"{progression.get('credit_count', 0)} / {progression.get('period_count', 0)}"),
                ))
        if hasattr(self, "staff_retention_tree"):
            prior_retention_selection = self.staff_retention_tree.selection() if hasattr(self.staff_retention_tree, "selection") else ()
            prior_retention_row = None
            if prior_retention_selection:
                prior_retention_row = getattr(self, "staff_retention_rows", {}).get(prior_retention_selection[0])
            self.staff_retention_tree.delete(*self.staff_retention_tree.get_children())
            self.staff_retention_rows = {}
            used_retention_rows = set()
            for index, member in enumerate(getattr(self, "staff", []) or []):
                progression = self.staff_progression_snapshot(member)
                remaining = progression.get("contract_months_remaining")
                contract_text = str(remaining) if remaining is not None else "Not available"
                concerns = ", ".join(progression.get("retention_concerns", [])) or "No flagged concern"
                base_row_id = self._staff_management_row_id(member, index, "staff-retention")
                row_id = base_row_id
                suffix = 2
                while row_id in used_retention_rows:
                    row_id = f"{base_row_id}#{suffix}"
                    suffix += 1
                used_retention_rows.add(row_id)
                self.staff_retention_rows[row_id] = member
                self.staff_retention_tree.insert("", "end", iid=row_id, values=(
                    progression.get("name", "Staff"), progression.get("role", "Operations"), contract_text,
                    concerns, f"{progression.get('credit_count', 0)} / {progression.get('period_count', 0)}",
                ))
            if hasattr(self.staff_retention_tree, "selection_set"):
                restored_id = None
                # Prefer the retained source object.  This is required for
                # opaque legacy rows whose deterministic content is identical;
                # a direct old Treeview ID could otherwise select the other
                # duplicate after a sort/reorder.
                if prior_retention_row is not None:
                    restored_id = next(
                        (row_id for row_id, member in self.staff_retention_rows.items()
                         if member is prior_retention_row),
                        None,
                    )
                # Durable saved IDs can survive a source reload that replaces
                # the Python object, so retain the old ID only when it resolves
                # to a row with the same saved staff identity.
                if restored_id is None and prior_retention_selection:
                    candidate = self.staff_retention_rows.get(prior_retention_selection[0])
                    if isinstance(candidate, dict) and str(candidate.get("staff_id", "") or "").strip():
                        restored_id = prior_retention_selection[0]
                if restored_id in self.staff_retention_tree.get_children():
                    self.staff_retention_tree.selection_set(restored_id)
        if hasattr(self, "staff_exception_tree"):
            self.staff_exception_tree.delete(*self.staff_exception_tree.get_children())
            raw_exceptions = state.get("exceptions", [])
            exceptions = raw_exceptions[-50:] if isinstance(raw_exceptions, list) else []
            used_exception_ids = set()
            for index, exception in enumerate(exceptions):
                if not isinstance(exception, dict):
                    continue
                base_id = self._staff_exception_view_id(exception, index)
                row_id = base_id
                suffix = 2
                while row_id in used_exception_ids:
                    row_id = f"{base_id}#{suffix}"
                    suffix += 1
                used_exception_ids.add(row_id)
                self.staff_exception_tree.insert("", "end", iid=row_id, values=(
                    exception.get("department", ""), exception.get("brief_id", ""),
                    exception.get("reason", ""), exception.get("boundary", ""),
                ))
        if hasattr(self, "staff_work_tree"):
            prior_work_key = ""
            prior_selection = self.staff_work_tree.selection()
            if prior_selection:
                prior_row = getattr(self, "staff_work_rows", {}).get(prior_selection[0], {})
                prior_work_key = self._staff_work_identity(prior_row)
            self.staff_work_tree.delete(*self.staff_work_tree.get_children())
            self.staff_work_rows = {}
            cards = self.foundation_work_cards(domain="staff", limit=50) if hasattr(self, "foundation_work_cards") else []
            if not cards:
                raw_work = state.get("work_log", [])
                raw_work = raw_work[-50:] if isinstance(raw_work, list) else []
                cards = [
                    {
                        "status_label": row.get("status", ""), "action": row.get("action_id", ""),
                        "target_id": row.get("target_ref", ""), "amount": row.get("spend", 0),
                        "evidence_key": row.get("evidence_key", ""), "operation_id": row.get("operation_id", ""),
                    }
                    for row in raw_work if isinstance(row, dict)
                ]
            raw_work_log = state.get("work_log", [])
            raw_work_log = raw_work_log if isinstance(raw_work_log, list) else []
            work_by_operation = {
                str(row.get("operation_id", "")): row
                for row in raw_work_log if isinstance(row, dict) and row.get("operation_id")
            }

            def safe_amount(value, fallback=0):
                try:
                    if isinstance(value, bool) or value is None or value == "":
                        raise ValueError
                    return max(0, int(value))
                except (TypeError, ValueError):
                    return fallback

            used_work_ids = set()
            retained_work_id = ""
            for index, card in enumerate(cards):
                if not isinstance(card, dict):
                    continue
                quoted = safe_amount(card.get("amount", 0))
                actual = safe_amount(card.get("actual_spend", card.get("spend", 0)))
                quote_label = "Unknown" if card.get("amount_state") == "Unknown" else f"${quoted:,}"
                actual_label = "Unknown" if card.get("actual_spend_state") == "Unknown" else f"${actual:,}"
                amount_text = quote_label if quote_label == actual_label or actual == 0 else f"{quote_label} / {actual_label}"
                if card.get("diagnostics"):
                    amount_text += "  ?"
                linked_work = work_by_operation.get(str(card.get("operation_id", "")), {})
                stored_card = deepcopy(card)
                if linked_work.get("work_id"):
                    stored_card["work_id"] = str(linked_work["work_id"])
                base_id = self._staff_work_view_id(stored_card, index=index)
                row_id = base_id
                duplicate = 2
                while row_id in used_work_ids:
                    row_id = f"{base_id}#{duplicate}"
                    duplicate += 1
                used_work_ids.add(row_id)
                self.staff_work_rows[row_id] = stored_card
                status_label = card.get("status_label", card.get("status", ""))
                display_action = linked_work.get("action_id", card.get("action", card.get("action_id", "")))
                if str(linked_work.get("status", "")).lower() == "recommendation":
                    status_label = "Advice ready"
                self.staff_work_tree.insert("", "end", iid=row_id, values=(
                    status_label,
                    self.STAFF_ACTION_LABELS.get(str(display_action), str(display_action)),
                    card.get("target_id", card.get("target_ref", "")), amount_text,
                    card.get("evidence_key", "") or "-", card.get("operation_id", "") or "-",
                ))
                if prior_work_key and self._staff_work_identity(stored_card) == prior_work_key and not retained_work_id:
                    retained_work_id = row_id
            if retained_work_id:
                self.staff_work_tree.selection_set(retained_work_id)

    def staff_refresh_capability_detail(self, _event=None):
        """Show the selected department's handler, scope and stop contract."""
        label = getattr(self, "staff_capability_detail", None)
        tree = getattr(self, "staff_capability_tree", None)
        if label is None or tree is None:
            return
        selected = tree.selection()
        department = str(selected[0]) if selected else ""
        row = next((item for item in self.staff_capability_matrix().values() if item.get("department") == department), None)
        if not row:
            label.config(text="Select a department to inspect its handler, target scope, cost/capacity boundary and stop conditions.")
            return
        actions = ", ".join(
            f"{item.get('label', item.get('id', 'Action'))} [{item.get('id', '')}]"
            f" ({'auto' if item.get('automation') else 'review'}; "
            f"{'registered' if item.get('handler_registered') else 'gated'})"
            for item in row.get("actions", [])
        ) or "None registered"
        safe_read_ids = ", ".join(row.get("safe_read_action_ids", [])) or "None registered"
        label.config(text=(
            f"{row.get('department')} | Execution: {row.get('execution_state', 'Gated')} | "
            f"Handler: {row.get('handler') or 'None'} | Actions: {actions}\n"
            f"Safe read-action IDs: {safe_read_ids}\n"
            f"Targets: {row.get('target_scope')}  Costs/capacity: {row.get('costs')} / {row.get('capacity')}\n"
            f"Stops: {row.get('stop_conditions')}  Evidence: {row.get('evidence')}"
        ))

    @staticmethod
    def _staff_work_identity(card):
        """Return a saved operation/work identity for receipt selection."""
        if not isinstance(card, dict):
            return ""
        for field in ("operation_id", "work_id"):
            identity = str(card.get(field, "") or "").strip()
            if identity:
                return f"staff-work:{identity}"
        return ""

    @classmethod
    def _staff_work_view_id(cls, card, index=0):
        """Build a UI row id without treating a list position as history."""
        identity = cls._staff_work_identity(card)
        if identity:
            return identity
        if isinstance(card, dict):
            payload = {
                "action_id": card.get("action_id", card.get("action", "")),
                "target_ref": card.get("target_ref", card.get("target_id", "")),
                "status": card.get("status", card.get("status_label", "")),
                "evidence_key": card.get("evidence_key", ""),
                "amount": card.get("amount", card.get("spend", "")),
            }
        else:
            payload = {"raw_type": type(card).__name__, "repr": repr(card)}
        payload.setdefault("raw_type", type(card).__name__)
        digest = hashlib.sha1(json.dumps(payload, sort_keys=True, default=str, separators=(",", ":")).encode("utf-8", "replace")).hexdigest()[:20]
        return f"staff-work-card:legacy:{digest}"

    @staticmethod
    def _staff_exception_view_id(exception, index=0):
        """Build a source-bound key for retained Staff exception evidence."""
        if isinstance(exception, dict):
            for field in ("exception_id", "operation_id", "work_id"):
                value = str(exception.get(field, "") or "").strip()
                if value:
                    return f"staff-exception:{value}"
            payload = {
                "department": exception.get("department", ""),
                "brief_id": exception.get("brief_id", ""),
                "reason": exception.get("reason", ""),
                "boundary": exception.get("boundary", ""),
            }
        else:
            payload = {"raw_type": type(exception).__name__, "repr": repr(exception)}
        payload.setdefault("raw_type", type(exception).__name__)
        digest = hashlib.sha1(json.dumps(payload, sort_keys=True, default=str, separators=(",", ":")).encode("utf-8", "replace")).hexdigest()[:20]
        return f"staff-exception:legacy:{digest}"
