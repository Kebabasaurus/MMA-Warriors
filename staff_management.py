        # This callback is also invoked by the Staff page repaint.  Read the
        # retained policy directly so a malformed/legacy envelope is not
        # normalised merely because the selector was refreshed.  Explicit
        # policy edits continue to own `ensure_staff_management_state`.
        state = getattr(self, "staff_management", {})
        if not isinstance(state, dict):
            state = {}
        mode = str(state.get("autonomy_mode", "Manual") or "Manual")
        if mode not in self.STAFF_AUTONOMY_MODES:
            mode = "Manual"
        if scope != "Company default":
            mode = self.staff_effective_autonomy(scope)
        if mode in self.STAFF_AUTONOMY_MODES:
            mode_var.set(mode)

