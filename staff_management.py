        if not raw_role:
            concerns.append("Missing role")
        try:
            current_month = int(getattr(self, "month", 1) or 1)
        except (TypeError, ValueError, OverflowError):
            current_month = 1
        current_year = max(1, (current_month - 1) // 12 + 1)
        raw_annual_gain = annual_gains.get(str(current_year), 0)
