    @staticmethod
    def _staff_management_row_id(member, index, prefix="staff"):
        """Build a stable identity for read-only Staff management tables."""
        if isinstance(member, dict):
            staff_id = str(member.get("staff_id", "") or "").strip()
            if staff_id:
                return f"{prefix}:{staff_id}"
            fields = ("name", "role", "specialty", "salary", "contract_months",
                      "contract_start_month", "contract_start_week", "contract_end_month",
                      "contract_end_week", "expiry_month", "expiry_week")
            payload = {field: member.get(field) for field in fields if member.get(field) not in (None, "")}
            if payload:
                digest = hashlib.sha1(json.dumps(payload, sort_keys=True, default=str, separators=(",", ":")).encode("utf-8")).hexdigest()[:16]
                return f"{prefix}:legacy:{digest}"
            # A completely empty/malformed legacy row has no source identity.
            # Keep it visible behind a deterministic opaque key; the refresh
            # path binds selection to the same retained object so duplicate
            # opaque rows cannot be reassociated by their sorted position.
            payload = {"raw_type": type(member).__name__, "raw_repr": repr(member)}
        else:
            payload = {"raw_type": type(member).__name__, "raw_repr": repr(member)}
        digest = hashlib.sha1(json.dumps(payload, sort_keys=True, default=str, separators=(",", ":")).encode("utf-8", "replace")).hexdigest()[:20]
        return f"{prefix}:legacy:opaque:{digest}"

    @staticmethod
    def _staff_brief_view_id(brief, index=0):
        """Build a deterministic presentation key for one saved brief.

        Brief IDs are authoritative when present.  A legacy row without one is
        still readable, so its retained planning fields provide a deterministic
        UI key rather than a mutable visible position.
        """
        if isinstance(brief, dict):
            brief_id = str(brief.get("brief_id", "") or "").strip()
            if brief_id:
                # Keep the established saved ID as the primary Treeview key;
                # duplicate rows receive a deterministic suffix at refresh.
                return brief_id
            payload = {
                "department": brief.get("department", ""),
                "objective": brief.get("objective", ""),
                "actions": brief.get("actions", []),
                "target_ref": brief.get("target_ref", ""),
                "created_month": brief.get("created_month", 0),
                "created_week": brief.get("created_week", 0),
            }
        else:
            payload = {"raw_type": type(brief).__name__, "repr": repr(brief)}
        payload.setdefault("raw_type", type(brief).__name__)
        digest = hashlib.sha1(json.dumps(payload, sort_keys=True, default=str, separators=(",", ":")).encode("utf-8", "replace")).hexdigest()[:20]
        return f"staff-brief:legacy:{digest}"

    @staticmethod
    def _staff_outcome_spend(outcome, *, recommendation=False):
        """Validate the inexpensive part of a handler response before budget checks."""
        if not isinstance(outcome, dict) or outcome.get("ok") is False:
            reason = (outcome or {}).get("reason", "The handler did not return a successful result.") if isinstance(outcome, dict) else "The handler did not return a successful result."
            return False, str(reason), 0
        try:
            spend = int(outcome.get("spend", 0) or 0)
        except (TypeError, ValueError):
            return False, "The handler returned an invalid spend amount.", 0
        if spend < 0:
            return False, "The handler returned a negative spend amount.", 0
        if recommendation and spend:
            return False, "Recommendation mode cannot return a paid action.", 0
        return True, "Spend is valid.", spend

    @staticmethod
    def _staff_validate_handler_outcome(action_id, outcome, *, recommendation=False):
        """Validate the evidence contract before a staff work row is sealed.

        Handlers are domain adapters, so the worker must not treat ``ok=True``
        as proof that work happened.  Every recorded action needs an evidence
        key and a structured result.  Recommendation handlers are additionally
        forbidden from returning spend: a read-only mode can explain work, but
        it cannot smuggle a paid commit through the advice path.  The returned
        copy is normalised without changing the handler's object or save state.
        """
        spend_ok, spend_reason, spend = StaffManagementMixin._staff_outcome_spend(
            outcome, recommendation=recommendation,
        )
        if not spend_ok:
            return False, spend_reason, None
        evidence_key = str(outcome.get("evidence_key", "") or "").strip()
        if not evidence_key:
            return False, "The handler returned no evidence key; the work cannot be sealed.", None
        # Older injected adapters did not include a result object.  Preserve
        # those callers as an empty, explicitly evidenced payload; live
        # handlers continue to provide their richer structured result.
        result = outcome.get("result", {})
        if result is None:
            result = {}
        if not isinstance(result, dict):
            return False, "The handler returned an invalid evidence payload.", None
        normalized = deepcopy(outcome)
        normalized["evidence_key"] = evidence_key
        normalized["spend"] = spend
        normalized["progression_eligible"] = bool(outcome.get("progression_eligible", False)) and spend > 0
        normalized["result"] = deepcopy(result)
        return True, "Evidence contract satisfied.", normalized

    def staff_capability_matrix(self):
        """Return the authored department capability contract as a read model.

        The matrix is intentionally independent of the staff worker: it tells
        the UI and audit what can be advised, what may be automated, which
        handler owns any action, and exactly where execution must stop. It
        reads raw saved policy/staff data without normalising the save.
        """
        raw_state = getattr(self, "staff_management", {})
        raw_state = raw_state if isinstance(raw_state, dict) else {}
        default_mode = str(raw_state.get("autonomy_mode", "Manual") or "Manual")
        if default_mode not in self.STAFF_AUTONOMY_MODES:
            default_mode = "Manual"
        overrides = raw_state.get("department_overrides", {})
        overrides = overrides if isinstance(overrides, dict) else {}
        matrix = {}
        handlers = self._staff_builtin_action_handlers()
        injected_handlers = getattr(self, "staff_action_handlers", {}) or {}
        if isinstance(injected_handlers, dict):
            handlers.update(injected_handlers)
        for department in self.STAFF_DEPARTMENTS:
            capability = self.STAFF_CAPABILITIES.get(department, {})
            mode = str(overrides.get(department, default_mode) or default_mode)
            if mode not in self.STAFF_AUTONOMY_MODES:
                mode = "Manual"
            # Select the same morale-adjusted lead as the live helper, but read
            # the raw collections directly so opening the matrix cannot repair
            # or normalise a saved policy as a side effect.
            role = {"Scouting": "Scout", "Matchmaking": "Matchmaker"}.get(department, department)
            candidates = [
                (index, member) for index, member in enumerate(getattr(self, "staff", []) or [])
                if isinstance(member, dict) and member.get("role") == role
            ]
            def lead_quality(pair):
                index, member = pair
                try:
                    skill = float(member.get("skill", 45) or 45)
                    morale = float(member.get("morale", 65) or 65)
                    if not math.isfinite(skill):
                        skill = 45.0
                    if not math.isfinite(morale):
                        morale = 65.0
                except (TypeError, ValueError, OverflowError):
                    skill, morale = 45.0, 65.0
                return (skill * (0.72 + morale / 230.0), skill, -index)
            lead = max(candidates, key=lead_quality)[1] if candidates else None
            actions = []
            for action_id in capability.get("actions", ()):
                action_id = str(action_id)
                handler_registered = callable(handlers.get(action_id))
                actions.append({
                    "id": action_id,
                    "label": self.STAFF_ACTION_LABELS.get(action_id, action_id),
                    "recommendation": action_id in self._staff_safe_recommendation_actions(capability),
                    "automation": bool(capability.get("automation")) and action_id not in self._staff_safe_recommendation_actions(capability),
                    "handler_registered": handler_registered,
                    "evidence_required": True,
                    "execution_state": "Registered" if handler_registered else "Gated",
                })
            registered = sum(1 for row in actions if row["handler_registered"])
            safe_read_action_ids = [
                row["id"] for row in actions if row["recommendation"]
            ]
            matrix[department] = {
                "department": department,
                "effective_mode": mode,
                "lead_id": str((lead or {}).get("staff_id", "") or ""),
                "lead_name": str((lead or {}).get("name", "Unstaffed") if lead else "Unstaffed"),
                "advice_available": bool(capability.get("advice")),
                "automation_available": bool(capability.get("automation")),
                # Preserve the original dictionary contract for existing
                # callers while exposing the explicit read-model names above.
                "advice": bool(capability.get("advice")),
                "automation": bool(capability.get("automation")),
                "handler": str(capability.get("handler", "") or ""),
                "actions": actions,
                # Keep the durable action IDs visible to the UI and audit.
                # Labels alone are ambiguous when a department exposes both
                # a read-only review and a mutating commit action.
                "safe_read_action_ids": safe_read_action_ids,
                "action_count": len(actions),
                "registered_action_count": registered,
                "execution_state": "Ready" if actions and registered == len(actions) else "Gated",
                "evidence_required": True,
                "costs": str(capability.get("costs", "No spend; no registered cost basis.") or ""),
                "capacity": str(capability.get("capacity", "No registered capacity source.") or ""),
                "target_scope": str(capability.get("target_scope", "No registered target scope.") or ""),
                "stop_conditions": str(capability.get("stop_conditions", "No registered stop conditions.") or ""),
                "evidence": str(capability.get("evidence", "No registered completion evidence.") or ""),
                "note": str(capability.get("note", "") or ""),
            }
        return deepcopy(matrix)

    def staff_evidence_audit(self, state=None):
        """Return a pure long-run qualification/evidence audit.

        This is a diagnostic read model over the saved Staff ledger.  It does
        not call ``ensure_staff_management_state`` (or any domain handler), so
        opening the audit cannot repair legacy rows, spend cash, consume RNG or
        award progression.  Findings are stable codes with a source identity
        to make a failed boundary actionable without relying on list position.
        """
        raw_state = state if isinstance(state, dict) else getattr(self, "staff_management", {})
        if not isinstance(raw_state, dict):
            raw_state = {}
        findings = []

        def add(code, message, *, work_id="", brief_id="", action_id="", boundary="", source="", staff_id=""):
            findings.append({
                "code": str(code), "message": str(message),
                "work_id": str(work_id or ""), "brief_id": str(brief_id or ""),
                "action_id": str(action_id or ""), "boundary": str(boundary or ""),
                "source": str(source or ""), "staff_id": str(staff_id or ""),
            })

        # Retain malformed rows as diagnostic findings instead of silently
        # dropping them.  The audit is deliberately read-only: it must never
        # normalise the saved envelope merely because the player opened it.
        raw_work_log = raw_state.get("work_log", [])
        work_rows = []
        if isinstance(raw_work_log, list):
            for index, row in enumerate(raw_work_log):
                if isinstance(row, dict):
                    work_rows.append(row)
                else:
                    add(
                        "invalid_work_row",
                        f"Staff work-log row {index + 1} is not a structured work record.",
                        source=f"work_log[{index}]",
                    )
        else:
            add(
                "invalid_work_collection",
                "Staff work log is not a list; retained work evidence cannot be trusted.",
                source="work_log",
            )

        raw_briefs = raw_state.get("briefs", [])
        briefs = []
        if isinstance(raw_briefs, list):
            for index, row in enumerate(raw_briefs):
                if isinstance(row, dict):
                    briefs.append(row)
                else:
                    add(
                        "invalid_brief_row",
                        f"Staff brief row {index + 1} is not a structured brief record.",
                        source=f"briefs[{index}]",
                    )
        else:
            add(
                "invalid_brief_collection",
                "Staff brief collection is not a list; retained brief evidence cannot be trusted.",
                source="briefs",
            )

        # Employment identity and obligations are hard evidence too.  Keep
        # this projection completely observational: do not call the profile
        # compatibility repair or any contract helper because opening the
        # audit must not rewrite legacy rows.  The player roster and shared
        # market are checked together so an ID collision cannot hide behind a
        # different source list.
        staff_identity_rows = {}

        def audit_staff_collection(source, members, *, present=True):
            if not present:
                return
            if not isinstance(members, list):
                add(
                    "invalid_staff_collection",
                    f"{source} staff collection is not a list; employment evidence cannot be trusted.",
                    source=source,
                )
                return
            for index, member in enumerate(members):
                if not isinstance(member, dict):
                    add(
                        "invalid_staff_row",
                        f"{source} staff row {index + 1} is not a structured employee record.",
                        source=source,
                    )
                    continue
                raw_staff_id = member.get("staff_id", "")
                staff_id = str(raw_staff_id or "").strip()
                label = str(member.get("name", "Unnamed staff") or "Unnamed staff").strip() or "Unnamed staff"
                if not staff_id:
                    add(
                        "missing_staff_identity",
                        f"{source} staff member {label} has no durable staff ID.",
                        source=source,
                    )
                else:
                    staff_identity_rows.setdefault(staff_id, []).append((source, label))
                role = member.get("role", "")
                if not isinstance(role, str) or not role.strip():
                    add(
                        "missing_staff_role",
                        f"{source} staff member {label} has no recorded role.",
                        source=source, staff_id=staff_id,
                    )

                raw_salary = member.get("salary", None)
                try:
                    salary = int(raw_salary) if not isinstance(raw_salary, bool) else None
                except (TypeError, ValueError, OverflowError):
                    salary = None
                # A missing salary can be a pre-profile legacy row and is
                # handled by the sanctioned load adapter.  Once a source row
                # carries a salary field, however, malformed and negative
                # values are hard evidence that must be surfaced here.
                if "salary" in member and (salary is None or salary < 0):
                    add(
                        "invalid_staff_salary",
                        f"{source} staff member {label} has an invalid or negative salary.",
                        source=source, staff_id=staff_id,
                    )

                raw_term = member.get("contract_months", None)
                try:
                    term = int(raw_term) if not isinstance(raw_term, bool) else None
                except (TypeError, ValueError, OverflowError):
                    term = None
                if "contract_months" in member and (term is None or term < 0):
                    add(
                        "invalid_staff_contract",
                        f"{source} staff member {label} has an invalid or negative contract term.",
                        source=source, staff_id=staff_id,
                    )

        audit_staff_collection("Employed roster", getattr(self, "staff", None), present=hasattr(self, "staff"))
        audit_staff_collection("Shared market", getattr(self, "staff_candidates", None), present=hasattr(self, "staff_candidates"))
        for staff_id, rows in staff_identity_rows.items():
            if len(rows) <= 1:
                continue
            sources = {source for source, _label in rows}
            if len(sources) > 1:
                message = f"Staff ID {staff_id} appears in both employed and shared-market evidence."
            else:
                message = f"Staff ID {staff_id} appears more than once in {next(iter(sources), 'staff')} evidence."
            add(
                "duplicate_staff_identity", message,
                source=" / ".join(sorted(sources)), staff_id=staff_id,
            )

        work_ids = {}
        operation_ids = {}
        executed_count = recommendation_count = qualified_count = 0
        boundaries = set()
        for row in work_rows:
            work_id = str(row.get("work_id", "") or "").strip()
            operation_id = str(row.get("operation_id", "") or "").strip()
            brief_id = str(row.get("brief_id", "") or "").strip()
            action_id = str(row.get("action_id", "") or "").strip()
            department = str(row.get("department", "") or "").strip()
            boundary = str(row.get("boundary", "") or "").strip()
            status = str(row.get("status", "") or "").strip()
            if boundary:
                boundaries.add(boundary)
            if work_id:
                work_ids.setdefault(work_id, []).append(row)
            if operation_id:
                operation_ids.setdefault(operation_id, []).append(row)
            if status in {"Executed", "Recommendation"}:
                if not work_id:
                    add(
                        "missing_work_identity",
                        "Staff work has no durable work ID.",
                        brief_id=brief_id, action_id=action_id, boundary=boundary,
                    )
                if not operation_id:
                    add(
                        "missing_operation_identity",
                        "Staff work has no durable operation ID.",
                        work_id=work_id, brief_id=brief_id, action_id=action_id,
                        boundary=boundary,
                    )
            if status == "Executed":
                executed_count += 1
                if row.get("progression_eligible") is True:
                    qualified_count += 1
                if not department or not action_id:
                    add("missing_work_identity", "Executed work is missing its department or action ID.", work_id=work_id, brief_id=brief_id, action_id=action_id, boundary=boundary)
                if not str(row.get("evidence_key", "") or "").strip():
                    add("missing_evidence", "Executed work has no evidence key.", work_id=work_id, brief_id=brief_id, action_id=action_id, boundary=boundary)
                try:
                    spend = int(row.get("spend", 0) or 0)
                except (TypeError, ValueError, OverflowError):
                    spend = -1
                if spend < 0:
                    add("invalid_spend", "Executed work has an invalid or negative spend amount.", work_id=work_id, brief_id=brief_id, action_id=action_id, boundary=boundary)
                if row.get("progression_eligible") is True and spend <= 0:
                    add("invalid_progression", "Progression is marked eligible without a positive spend.", work_id=work_id, brief_id=brief_id, action_id=action_id, boundary=boundary)
                allowed = self.STAFF_CAPABILITIES.get(department, {}).get("actions", ())
                if action_id not in {str(value) for value in allowed}:
                    add("unsupported_action", f"Executed action is not registered for {department or 'the department'}.", work_id=work_id, brief_id=brief_id, action_id=action_id, boundary=boundary)
            elif status == "Recommendation":
                recommendation_count += 1
                try:
                    spend = int(row.get("spend", 0) or 0)
                except (TypeError, ValueError, OverflowError):
                    spend = -1
                if spend != 0:
                    add("paid_recommendation", "Recommendation work must remain zero-spend.", work_id=work_id, brief_id=brief_id, action_id=action_id, boundary=boundary)
                recommendations = row.get("recommendations", [])
                if not isinstance(recommendations, list):
                    add("invalid_recommendation_payload", "Recommendation work has no structured recommendation list.", work_id=work_id, brief_id=brief_id, action_id=action_id, boundary=boundary)
                else:
                    for recommendation in recommendations:
                        if not isinstance(recommendation, dict):
                            add("invalid_recommendation_payload", "Recommendation entry is not structured evidence.", work_id=work_id, brief_id=brief_id, action_id=action_id, boundary=boundary)
                            continue
                        if str(recommendation.get("status", "") or "") == "Ready" and not str(recommendation.get("evidence_key", "") or "").strip():
                            add("missing_evidence", "Ready recommendation has no evidence key.", work_id=work_id, brief_id=brief_id, action_id=str(recommendation.get("action_id", action_id) or action_id), boundary=boundary)
            elif status not in {"", "Queued", "Needs attention"}:
                add(
                    "unsupported_work_status",
                    f"Staff work uses unsupported status {status!r}.",
                    work_id=work_id, brief_id=brief_id, action_id=action_id,
                    boundary=boundary,
                )

        for work_id, rows in work_ids.items():
            if len(rows) > 1:
                add("duplicate_work_id", "Work ID appears more than once in the saved ledger.", work_id=work_id)
        for operation_id, rows in operation_ids.items():
            if len(rows) > 1:
                add("duplicate_operation_id", "Operation ID appears more than once in the saved ledger.", work_id=str(rows[0].get("work_id", "") or ""), brief_id=str(rows[0].get("brief_id", "") or ""))

        for brief in briefs:
            brief_id = str(brief.get("brief_id", "") or "").strip()
            allowed = [str(value) for value in brief.get("allowed_action_ids", []) or [] if value]
            completed = {str(value) for value in brief.get("completed_action_ids", []) or [] if value}
            if not isinstance(brief.get("allowed_action_ids", []), list):
                add("invalid_brief_actions", "Brief action allow-list is not a list.", brief_id=brief_id)
            unknown_completed = sorted(completed - set(allowed))
            for action_id in unknown_completed:
                add("completed_action_not_allowlisted", "Brief records a completed action outside its saved allow-list.", brief_id=brief_id, action_id=action_id)
            if str(brief.get("status", "") or "") == "Completed" and set(allowed) - completed:
                add("incomplete_brief_sealed", "Completed brief still has an allow-listed action without a completion key.", brief_id=brief_id)

        raw_progression = raw_state.get("progression", {})
        if isinstance(raw_progression, dict):
            progression = raw_progression
        else:
            progression = {}
            add(
                "invalid_progression_collection",
                "Staff progression ledger is not a mapping; retained credits cannot be trusted.",
                source="progression",
            )
        known_work_ids = set(work_ids)
        for staff_id, row in progression.items():
            if not isinstance(row, dict):
                add("invalid_progression_row", "Progression entry is not structured.", brief_id=str(staff_id or ""))
                continue
            raw_credited_work_ids = row.get("credited_work_ids", [])
            if not isinstance(raw_credited_work_ids, list):
                add(
                    "invalid_progression_credits",
                    "Progression entry has no structured credited-work list.",
                    brief_id=str(staff_id or ""), staff_id=str(staff_id or ""),
                )
                raw_credited_work_ids = []
            for work_id in raw_credited_work_ids:
                work_id = str(work_id or "").strip()
                if work_id and work_id not in known_work_ids:
                    add("orphaned_progression", "Progression references work that is not in the retained ledger.", work_id=work_id)

        findings.sort(key=lambda row: (
            row["code"], row["source"], row["staff_id"], row["boundary"],
            row["brief_id"], row["work_id"], row["action_id"],
        ))
        return {
            "schema_version": 1,
            "status": "Healthy" if not findings else "Needs attention",
            "work_count": len(work_rows), "executed_count": executed_count,
            "recommendation_count": recommendation_count, "qualified_count": qualified_count,
            "boundary_count": len(boundaries), "finding_count": len(findings),
            "findings": deepcopy(findings),
        }

