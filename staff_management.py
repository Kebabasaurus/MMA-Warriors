    def set_staff_autonomy(self, mode, department=None):
        state = self.ensure_staff_management_state()
        mode = str(mode or "Manual")
        if mode not in self.STAFF_AUTONOMY_MODES:
            return False, "Choose Manual, Recommendations, Selective Recommendations or Full Auto.", deepcopy(state)
        if department and str(department) not in self.STAFF_DEPARTMENTS:
            return False, "That department is not recognised.", deepcopy(state)
        if department:
            state.setdefault("department_overrides", {})[str(department)] = mode
            scope = str(department)
        else:
            state["autonomy_mode"] = mode
            scope = "company"
        state["revision"] = int(state.get("revision", 1) or 1) + 1
        return True, f"{scope.title()} autonomy is now {mode}. Only uncommitted work is affected.", deepcopy(state)

